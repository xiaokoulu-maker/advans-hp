/** カード表示用のサマリー（一覧・関連サービスで使用） */
export function getServiceSummary(slug: ServiceSlug) {
  const card = services.find((s) => s.slug === slug)!;
  const detail = serviceDetails.find((s) => s.slug === slug)!;
  return { slug, no: card.no, title: card.title, body: card.body, en: detail.en };
}

export type ServiceSummary = ReturnType<typeof getServiceSummary>;
